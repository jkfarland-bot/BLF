#!/usr/bin/env python3
"""Generate BLF/CheckN.lean: the search check for n split at the first two search indices into
small kernel-checked pieces (one declaration each), combined with BLF.search_split."""
import sys, re
n = int(sys.argv[1]); B = n
data = open(f"/home/claude/blf/BLF/Data{n}.lean").read()
order = [int(t) for t in re.search(r"def order : List ℕ := \[([^\]]*)\]", data).group(1).split(",")]
k1, k2 = order[0], order[1]
vals = list(range(-B, B + 1))
L = f"(fun g => masks.contains (bitsVal (parList (2 ^ {n}) g)))"
S = f"search cons (fun _ => {n}) {L}"
lst = "[" + ", ".join(str(v) for v in vals) + "]"
def z(v): return f"({v} : ℤ)"
out = [f"module\n\npublic import BLF.Data{n}\n\n@[expose] public section\n",
       f"/-! The search check for n = {n}, split into {len(vals)**2} kernel-checked pieces (generated by scripts/gen_split.py). -/\n",
       "namespace BLF\n", f"namespace N{n}\n",
       "def masks : List ℕ := wits.map (fun w => bitsVal w.1)\n",
       f"def rest : List ℕ := order.drop 2\n",
       f"theorem order_eq : order = {k1} :: {k2} :: rest := rfl\n",
       f"theorem rangeZ_eq : rangeZ {B} = ({lst} : List ℤ) := by decide\n"]
def g1(a): return f"(Function.update (fun _ => (0 : ℤ)) {k1} {z(a)})"
def g2(a, b): return f"(Function.update {g1(a)} {k2} {z(b)})"
for i, a in enumerate(vals):
    for j, b in enumerate(vals):
        out.append(f"theorem piece_{i}_{j} : (cons {k1}).all (okQ {g1(a)}) = true →\n    (cons {k2}).all (okQ {g2(a,b)}) = true →\n    {S} rest {g2(a,b)} = true := by\n  decide +kernel\n")
cases = " | ".join(["rfl"] * len(vals))
for i, a in enumerate(vals):
    body = "\n".join(f"  · exact piece_{i}_{j} h1" for j in range(len(vals)))
    out.append(f"""theorem level_{i} : (cons {k1}).all (okQ {g1(a)}) = true →
    {S} ({k2} :: rest) {g1(a)} = true := by
  intro h1
  rw [search_split]
  intro w hw
  rw [rangeZ_eq] at hw
  simp only [List.mem_cons, List.not_mem_nil, or_false] at hw
  rcases hw with {cases}
{body}
""")
body = "\n".join(f"  · exact level_{i}" for i in range(len(vals)))
out.append(f"""theorem check : {S} order (fun _ => 0) = true := by
  rw [order_eq, search_split]
  intro v hv
  rw [rangeZ_eq] at hv
  simp only [List.mem_cons, List.not_mem_nil, or_false] at hv
  rcases hv with {cases}
{body}
""")
out.append(f"end N{n}\n\nend BLF\n")
open(f"/home/claude/blf/BLF/Check{n}.lean", "w").write("\n".join(out))
