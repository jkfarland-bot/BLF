#!/usr/bin/env python3
"""Generate BLF/CheckN.lean: the search check for n, split recursively at the first D search indices
into small kernel-checked pieces (one declaration each), combined with BLF.search_split."""
import sys, re, itertools
n = int(sys.argv[1]); D = int(sys.argv[2])
data = open(f"/home/claude/blf/BLF/Data{n}.lean").read()
order = [int(t) for t in re.search(r"def order : List ℕ := \[([^\]]*)\]", data).group(1).split(",")]
ks = order[:D]
def bnd(k): return bin(k).count("1") - 1
L = f"(fun g => masks.contains (bitsVal (parList (2 ^ {n}) g)))"
S = f"search cons bnd {L}"
out = [f"module\n\npublic import BLF.Data{n}\n\n@[expose] public section\n",
       f"/-! The search check for n = {n}, split at the first {D} search indices (generated by scripts/gen_split.py). -/\n",
       "namespace BLF\n", f"namespace N{n}\n",
       "def masks : List ℕ := wits.map (fun w => bitsVal w.1)\n",
       f"def rest : List ℕ := order.drop {D}\n",
       f"theorem order_eq : order = " + " :: ".join(map(str, ks)) + " :: rest := rfl\n"]
for k in ks:
    B = bnd(k)
    out.append(f"theorem rangeZ_{k} : rangeZ (bnd {k}) = (["
               + ", ".join(str(v) for v in range(-B, B + 1)) + "] : List ℤ) := by decide\n")
def g(path):
    t = "(fun _ => (0 : ℤ))"
    for k, v in zip(ks, path): t = f"(Function.update {t} {k} ({v} : ℤ))"
    return t
def name(path): return "node_" + "_".join(str(v + 10) for v in path)
def prem(path):
    return "".join(f"(cons {ks[i]}).all (okQ {g(path[:i+1])}) = true →\n    " for i in range(len(path)))
def tail(d): return "rest" if d == D else "(" + " :: ".join(map(str, ks[d:])) + " :: rest)"
nodes = []
def rec(path):
    d = len(path)
    if d == D:
        nodes.append(f"theorem {name(path)} : {prem(path)}{S} rest {g(path)} = true := by\n  decide +kernel\n")
        return
    k = ks[d]; B = bnd(k); vals = list(range(-B, B + 1))
    for v in vals: rec(path + [v])
    hs = " ".join(f"h{i}" for i in range(d))
    intro = f"  intro {hs}\n" if d else ""
    body = "\n".join(f"  · exact {name(path + [v])}" + (f" {hs}" if d else "") for v in vals)
    stmt = f"{prem(path)}{S} {tail(d)} {g(path)} = true" if d else f"{S} order (fun _ => 0) = true"
    pre = "" if d else "  rw [order_eq]\n"
    nodes.append(f"theorem {'check' if d == 0 else name(path)} : {stmt} := by\n{intro}{pre}  rw [search_split]\n"
                 f"  intro w hw\n  rw [rangeZ_{k}] at hw\n  simp only [List.mem_cons, List.not_mem_nil, or_false] at hw\n"
                 f"  rcases hw with " + " | ".join(["rfl"] * len(vals)) + "\n" + body + "\n")
rec([])
out += nodes
out.append(f"end N{n}\n\nend BLF\n")
open(f"/home/claude/blf/BLF/Check{n}.lean", "w").write("\n".join(out))
print(f"{sum(1 for x in nodes if 'decide +kernel' in x)} leaves, {len(nodes)} theorems", file=sys.stderr)
