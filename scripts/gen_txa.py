#!/usr/bin/env python3
"""Generate BLF/TxaN.lean: for every canonical BLF class table (from BLF/DataN.lean), either a
threshold function T = [w0 + w.x > 0] and an affine function (c, b) with table = T XOR affine,
or (for n = 4) the affine function with table = (bit 1 of x1 + ... + x4) XOR affine."""
import itertools, re, sys
n = int(sys.argv[1]); N = 1 << n
data = open(f"/home/claude/blf/BLF/Data{n}.lean").read()
tables = [tuple(1 if b.strip() == "true" else 0 for b in m.group(1).split(","))
          for m in re.finditer(r"\(\[([^\]]*)\], \d+, -?\d+, \[", data)]
def bits(k): return [(k >> i) & 1 for i in range(n)]
def aff_of(T):
    c = T[0]; b = [T[1 << i] ^ c for i in range(n)]
    A = tuple(c ^ (sum(b[i] & bits(x)[i] for i in range(n)) & 1) for x in range(N))
    return (c, b) if A == T else None
thr = {}
W = 3 if n <= 4 else 9
for w in itertools.product(range(-W, W + 1), repeat=n):
    for w0 in range(-n * W - 1, n * W + 2):
        T = tuple(int(w0 + sum(wi * xi for wi, xi in zip(w, bits(x))) > 0) for x in range(N))
        if T not in thr: thr[T] = (w0, w)
g = tuple((bin(x).count("1") >> 1) & 1 for x in range(N))
tw, sp = [], []
for s in tables:
    found = None
    for T, (w0, w) in thr.items():
        A = tuple(a ^ b for a, b in zip(s, T))
        ab = aff_of(A)
        if ab: found = (w0, w, ab); break
    if found: tw.append((s, found))
    else:
        ab = aff_of(tuple(a ^ b for a, b in zip(s, g)))
        assert ab, "class neither threshold XOR affine nor g XOR affine"
        sp.append((s, ab))
print(f"n={n}: {len(tables)} classes, {len(tw)} threshold XOR affine, {len(sp)} special", file=sys.stderr)
def lb(v): return "true" if v else "false"
def tab(s): return "[" + ", ".join(lb(v) for v in s) + "]"
out = [f"module\n\npublic import BLF.Small{n}\npublic import BLF.Txa\n\n@[expose] public section\n",
       f"/-! Threshold-XOR-affine witnesses for n = {n} (generated by scripts/gen_txa.py; kernel-checked). -/\n",
       "set_option maxHeartbeats 4000000\n", "namespace BLF\n", f"namespace N{n}\n"]
CH = 40
chunks = [tw[i:i + CH] for i in range(0, len(tw), CH)] or [[]]
for ci, ch in enumerate(chunks):
    out.append(f"def tws{ci} : List TW := [" + ",\n  ".join(
        f"({tab(s)}, {w0}, [" + ", ".join(map(str, w)) + f"], {lb(c)}, [" + ", ".join(lb(v) for v in b) + "])"
        for s, (w0, w, (c, b)) in ch) + "]\n")
    out.append(f"theorem twOk{ci} : tws{ci}.all (twOk {n}) = true := by decide +kernel\n")
out.append("def tws : List TW := " + " ++ ".join(f"tws{ci}" for ci in range(len(chunks))) + "\n")
out.append("theorem twOk' : tws.all (twOk %d) = true := by\n  simp only [tws, List.all_append, " % n
           + ", ".join(f"twOk{ci}" for ci in range(len(chunks))) + ", Bool.and_self]\n")
out.append("def sps : List SP := [" + ",\n  ".join(
    f"({tab(s)}, {lb(c)}, [" + ", ".join(lb(v) for v in b) + "])" for s, (c, b) in sp) + "]\n")
open(f"/home/claude/blf/BLF/TxaData{n}.lean", "w").write("\n".join(out) + f"\nend N{n}\n\nend BLF\n")
