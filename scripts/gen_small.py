#!/usr/bin/env python3
"""Generate BLF/SmallN.lean: data for BLF.small_count (relations, search order, witnesses).
Witnesses: for every canonical class table s (s(0) = s(e_i) = 0) found on the grid, integers
(j, K, a) with bit j of K + a.x equal to s at every vertex. The Lean kernel rechecks all of it."""
import itertools, sys
n = int(sys.argv[1]); N = 1 << n
def bits(k): return [(k >> i) & 1 for i in range(n)]
# relations x + y = z + w (cube vertices), canonical orientation, {x,y} != {z,w}
quads = set()
for x in range(N):
    for y in range(x, N):
        for z in range(N):
            for w in range(z, N):
                if (x, y) >= (z, w): continue
                if all(bits(x)[i] + bits(y)[i] == bits(z)[i] + bits(w)[i] for i in range(n)):
                    quads.add((x, y, z, w))
# the chain quads (k, 0, k - lowbit, lowbit) used for pruning
for k in range(N):
    if bin(k).count('1') >= 2:
        lb = k & -k
        quads.add((k, 0, k - lb, lb))
fixed = {0} | {1 << i for i in range(n)}
order = sorted([k for k in range(N) if k not in fixed], key=lambda k: (bin(k).count('1'), k))
pos = {k: i for i, k in enumerate(order)}
cons = {k: [] for k in order}
for q in sorted(quads):
    m = max((pos.get(v, -1) for v in q))
    if m >= 0: cons[order[m]].append(q)
# witnesses
def canon(T):
    f0 = T[0]; b = [T[1 << i] ^ f0 for i in range(n)]
    return tuple(T[x] ^ f0 ^ (sum(b[i] & bits(x)[i] for i in range(n)) & 1) for x in range(N))
wit = {}
for j in range(0, 6):
    M = 1 << (j + 1)
    for a in itertools.product(range(M), repeat=n):
        for K in range(M):
            T = tuple(((K + sum(ai * bi for ai, bi in zip(a, bits(x)))) >> j) & 1 for x in range(N))
            if T == canon(T) and T not in wit: wit[T] = (j, K, a)
    if j >= n - 1: break
print(f"n={n}: {len(quads)} quads, {len(order)} order, {len(wit)} canonical witnessed classes", file=sys.stderr)
def lb(b): return "true" if b else "false"
out = [f"module\n\npublic import BLF.Small\n\n@[expose] public section\n\n/-! Data for n = {n}, generated by scripts/gen_small.py; every fact is rechecked by the kernel. -/\n",
       "namespace BLF\n", f"namespace N{n}\n"]
out.append("def allQ : List Quad := [" + ", ".join(f"({a}, {b}, {c}, {d})" for a, b, c, d in sorted(quads)) + "]\n")
out.append("def consTable : List (ℕ × List Quad) := [" + ",\n  ".join(
    f"({k}, [" + ", ".join(f"({a}, {b}, {c}, {d})" for a, b, c, d in cons[k]) + "])" for k in order) + "]\n")
out.append("def cons (k : ℕ) : List Quad := ((consTable.find? (·.1 == k)).map (·.2)).getD []\n")
out.append("def order : List ℕ := [" + ", ".join(map(str, order)) + "]\n")
out.append("def wits : List Wit := [" + ",\n  ".join(
    "([" + ", ".join(lb(b) for b in T) + f"], {j}, {K}, [" + ", ".join(map(str, a)) + "])"
    for T, (j, K, a) in sorted(wit.items())) + "]\n")
open(f"/home/claude/blf/BLF/Data{n}.lean", "w").write("\n".join(out) + f"\nend N{n}\n\nend BLF\n")
