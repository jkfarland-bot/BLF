/* R_n = number of chambers of the toric arrangement {p in T^(n+1) : v_x . p in Z}, v_x = (1, x),
   x in {0,1}^n, by the vertex formula  R = sum over toric vertices p of |mu(p, top)|,
   with |mu(p, top)| = number of no-broken-circuit bases of the local vector matroid
   M_p = {v_y : v_y . p in Z} (Rota / Ehrenborg-Readdy-Slone / Moci).
   Equivalently: R = sum over bases B of #{p : B p in Z^(n+1) mod Z^(n+1), no y in M_p \ B is
   externally active for B}. y is externally active if y < min of the elements of B that appear
   with nonzero coefficient in v_y's expansion in B (order = index x).
   No grid, no LP. usage: nbc n [part nparts] */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <math.h>
typedef long long ll;
static int n, d, N;
static int V[128][8];
static int b[8];
static ll total = 0, nbases = 0, dsum = 0;
static int part = 0, nparts = 1;
/* exact integer determinant (Bareiss) */
static ll det_exact(int m[8][8], int k) {
    ll a[8][8]; int sign = 1; ll prev = 1;
    for (int i = 0; i < k; i++) for (int j = 0; j < k; j++) a[i][j] = m[i][j];
    for (int c = 0; c < k - 1; c++) {
        if (a[c][c] == 0) {
            int p = -1; for (int i = c + 1; i < k; i++) if (a[i][c]) { p = i; break; }
            if (p < 0) return 0;
            for (int j = 0; j < k; j++) { ll t = a[c][j]; a[c][j] = a[p][j]; a[p][j] = t; } sign = -sign;
        }
        for (int i = c + 1; i < k; i++) for (int j = c + 1; j < k; j++) a[i][j] = (a[i][j] * a[c][c] - a[i][c] * a[c][j]) / prev;
        prev = a[c][c];
    }
    return sign * a[k - 1][k - 1];
}
static void leaf(void) {
    int B[8][8];
    for (int i = 0; i < d; i++) memcpy(B[i], V[b[i]], sizeof(int) * 8);
    ll D = det_exact(B, d);
    if (D == 0) return;
    ll ad = D < 0 ? -D : D;
    /* adj = D * B^{-1}, via double Gauss-Jordan then rounding, then exact check B*adj = D*I */
    double M[8][16];
    for (int i = 0; i < d; i++) { for (int j = 0; j < d; j++) { M[i][j] = B[i][j]; M[i][d + j] = (i == j); } }
    for (int c = 0; c < d; c++) {
        int p = c; for (int i = c; i < d; i++) if (fabs(M[i][c]) > fabs(M[p][c])) p = i;
        for (int j = 0; j < 2 * d; j++) { double t = M[c][j]; M[c][j] = M[p][j]; M[p][j] = t; }
        double pv = M[c][c]; for (int j = 0; j < 2 * d; j++) M[c][j] /= pv;
        for (int i = 0; i < d; i++) if (i != c) { double f = M[i][c]; if (f != 0) for (int j = 0; j < 2 * d; j++) M[i][j] -= f * M[c][j]; }
    }
    ll adj[8][8];
    for (int i = 0; i < d; i++) for (int j = 0; j < d; j++) adj[i][j] = llround(M[i][d + j] * (double)D);
    for (int i = 0; i < d; i++) for (int j = 0; j < d; j++) {
        ll s = 0; for (int k = 0; k < d; k++) s += (ll)B[i][k] * adj[k][j];
        if (s != (i == j ? D : 0)) { fprintf(stderr, "adj check failed\n"); exit(2); }
    }
    nbases++; dsum += ad;
    /* candidate externally active y: y not in B, y < min support of w_y = v_y adj */
    int cand[128], nc = 0; int inB[128] = {0};
    for (int i = 0; i < d; i++) inB[b[i]] = 1;
    for (int y = 0; y < b[d - 1]; y++) if (!inB[y]) {
        int mn = 1 << 30;
        for (int k = 0; k < d; k++) { ll s = 0; for (int i = 0; i < d; i++) s += (ll)V[y][i] * adj[i][k]; if (s) { if (b[k] < mn) mn = b[k]; } }
        if (y < mn) cand[nc++] = y;
    }
    /* points p = P / ad, P in Z_ad^d, generated by the columns of adj (sign irrelevant) */
    static int pts[64][8]; int np = 1; memset(pts[0], 0, sizeof(pts[0]));
    for (int k = 0; k < d && np < ad; k++) {
        int g[8]; for (int i = 0; i < d; i++) { ll v = adj[i][k] % ad; if (v < 0) v += ad; g[i] = (int)v; }
        /* closure: add multiples of g to all current points */
        int cur = np;
        for (int h = 0; h < np; h++) {
            int P[8]; for (int i = 0; i < d; i++) P[i] = (pts[h][i] + g[i]) % ad;
            int found = 0; for (int e = 0; e < np; e++) if (!memcmp(pts[e], P, sizeof(int) * d)) { found = 1; break; }
            if (!found) { memcpy(pts[np++], P, sizeof(int) * d); }
            (void)cur;
        }
    }
    if (np != ad) { fprintf(stderr, "group size %d != %lld\n", np, ad); exit(3); }
    for (int h = 0; h < np; h++) {
        int bad = 0;
        for (int c = 0; c < nc && !bad; c++) {
            ll s = 0; for (int i = 0; i < d; i++) s += (ll)V[cand[c]][i] * pts[h][i];
            if (s % ad == 0) bad = 1;
        }
        if (!bad) total++;
    }
}
static void rec(int start, int depth) {
    if (depth == d) { leaf(); return; }
    for (int i = start; i <= N - (d - depth); i++) {
        if (depth == 0 && (i % nparts) != part) continue;
        b[depth] = i; rec(i + 1, depth + 1);
    }
}
int main(int argc, char **argv) {
    n = atoi(argv[1]); d = n + 1; N = 1 << n;
    if (argc > 3) { part = atoi(argv[2]); nparts = atoi(argv[3]); }
    for (int x = 0; x < N; x++) { V[x][0] = 1; for (int i = 0; i < n; i++) V[x][1 + i] = (x >> i) & 1; }
    rec(0, 0);
    printf("n=%d part=%d/%d bases=%lld D=%lld R=%lld\n", n, part, nparts, nbases, dsum, total);
    return 0;
}
